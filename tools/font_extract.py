#!/usr/bin/env python3
"""Extract the original's font style table from the user's installation.

    python tools/font_extract.py
    python tools/font_extract.py --lbx /path/to/FONTS.LBX --out fonts.json

Makes the pixel heights of the original's text styles a transcription, not
a measurement off a screenshot: entry 0 of FONTS.LBX is the font blob
`fonts::Load_Font_File` loads (fonts.cpp:880-902, `Farload(filename, 0)`):
the glass colours (16 x 4 bytes, `video::glass_colors`), then `s_font`
(orion2.h:869), whose `font_heights`, `font_spacing` and `leading_extra`
are what `Set_Font_Style` copies for a style index (fonts.cpp:135-154).

**GENERATED, NEVER COMMITTED** (decisions 38, 40, 42) — it is the user's
game data; the output goes to `assets/shared/fonts/font_styles.json` (ignored by git, registered in `tools/setup.py` `from_game`).
"""
import argparse
import json
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tools"))

from core import lbx  # noqa: E402
from core import paths  # noqa: E402

LBX_NAME = "FONTS.LBX"
OUT_DEFAULT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "assets", "shared", "fonts", "font_styles.json")
GLASS_BYTES = 16 * 4          # video.h:51 glass_colors[16], 4 bytes each
# offsets inside s_font (orion2.h:869-887): selected_colors 8, height 2,
# style 2, three colour arrays 24, current_height/line_height/leading/
# spacing 8, widths 256, offsets 1024 -> font_heights
HEIGHTS_AT = GLASS_BYTES + 8 + 2 + 2 + 24 + 8 + 256 + 1024
STYLES = 6                    # font_glyph_widths[6][256]; arrays hold 8
S_FONT_BYTES = 9052


def find(folder, filename):
    """The file in `folder`, whatever case the installation uses."""
    if not os.path.isdir(folder):
        return None
    for name in os.listdir(folder):
        if name.lower() == filename.lower():
            return os.path.join(folder, name)
    return None


def styles(blob):
    """One dict per style index the game can select."""
    if len(blob) < GLASS_BYTES + S_FONT_BYTES:
        sys.exit(f"entry 0: {len(blob)} bytes, "
                 f"{GLASS_BYTES + S_FONT_BYTES} needed (orion2.h:869)")
    heights = struct.unpack_from("<8h", blob, HEIGHTS_AT)
    spacing = struct.unpack_from("<8h", blob, HEIGHTS_AT + 16)
    leading = struct.unpack_from("<8h", blob, HEIGHTS_AT + 32)
    widths_at = HEIGHTS_AT + 48
    out = []
    for i in range(STYLES):
        widths = struct.unpack_from("<256b", blob, widths_at + i * 256)
        out.append({"style": i, "height": heights[i], "spacing": spacing[i],
                    "leading": leading[i], "line_height":
                    heights[i] + leading[i], "widths": list(widths)})
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lbx", default=None)
    parser.add_argument("--out", default=None)
    args = parser.parse_args()
    path = args.lbx or find(paths.game_dir(), LBX_NAME)
    if not path or not os.path.exists(path):
        sys.exit(f"{LBX_NAME} not found. Point --lbx at your own "
                 f"installation's copy.")
    doc = {"_comment": "Generated by tools/font_extract.py from the "
                       "player's own FONTS.LBX. Never committed.",
           "_source": "fonts.cpp:135-154, :880-902, orion2.h:869",
           "styles": styles(lbx.read_entry(path, 0))}
    out = args.out or OUT_DEFAULT
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as handle:
        json.dump(doc, handle, indent=2)
        handle.write("\n")
    print(", ".join(f"style {s['style']}: {s['height']}px"
                    for s in doc["styles"]) + f" -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
